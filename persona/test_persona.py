#!/usr/bin/env python3
"""Session 1.2 Part 5 -- the moment of truth: does the persona sound like you?

Same idea as the guide's script (persona only, no retrieval yet), with three fixes:
  * uses each relationship's MEASURED style (the guide used one global hinglish_ratio)
  * runs every reply through the guardrail and prints violations -- the v1 run produced
    replies that confirmed plans and invented a flight booking, and nobody noticed
  * writes persona/sample_outputs.md (the Week 1 deliverable) automatically

    python3 persona/test_persona.py        # needs GEMINI_API_KEY in .env
"""
import json
import os
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from dotenv import load_dotenv  # noqa: E402
from google import genai  # noqa: E402

from agent.generator import build_prompt  # noqa: E402
from agent.guardrail import check, clean  # noqa: E402

load_dotenv(ROOT / ".env")
client = genai.Client(api_key=os.getenv("GEMINI_API_KEY"))
MODEL = os.getenv("GEMINI_MODEL", "gemini-3.5-flash")
persona = json.loads((ROOT / "persona" / "persona.json").read_text(encoding="utf-8"))

test_prompts = [  # the guide's three + two more so you can pick the best 5
    ("wife", "I am going to be late today, can you pick me up?", "hold"),
    ("family", "diwali pe ghar aaoge kya?", "hold"),
    ("professional", "I have a new video ready when can we connect?", "hold"),
    ("wife", "Tumne kha liya khana?", "reply"),
    ("family", "Reached home safely 😊", "reply"),
    ("professional", "We crossed 1000 registrations!!", "reply"),
]

lines = ["# Persona Sample Outputs", "", f"Generated by `persona/test_persona.py` with `{MODEL}` (persona only, no retrieval).", ""]
for relationship, incoming, mode in test_prompts:
    prompt = build_prompt(persona, relationship, incoming, retrieved=[], context_rows=[], mode=mode)
    reply = clean(client.models.generate_content(model=MODEL, contents=prompt).text or "")
    problems = check(reply, incoming, "", mode, 40)
    flag = "✅" if not problems else "⛔ " + "; ".join(problems)
    print(f"[{relationship}] {incoming} -> {reply}   {flag}")
    lines += [f"## {relationship.title()} ({mode})", "", f"**Incoming:** `{incoming}`", "", f"> {reply}", "", f"Guardrail: {flag}", ""]
(ROOT / "persona" / "sample_outputs.md").write_text("\n".join(lines), encoding="utf-8")
print("Saved persona/sample_outputs.md -- keep the 5 that sound most like you.")
